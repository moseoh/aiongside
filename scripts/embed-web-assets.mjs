import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Turns the Vite build in packages/web/ui/dist into a TypeScript module that
 * the CLI bundle embeds, so the published package stays a single bin.js.
 */
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "packages/web/ui/dist");
const target = path.join(root, "packages/web/src/assets.generated.ts");
const LIMIT = 1.5 * 1024 * 1024;

const types = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
  ".json": "application/json; charset=utf-8",
  ".txt": "text/plain; charset=utf-8",
};

async function walk(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const item = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(item)));
    else if (entry.isFile()) files.push(item);
  }
  return files.sort();
}

try {
  await stat(path.join(source, "index.html"));
} catch {
  throw new Error(
    `Missing ${path.relative(root, source)}/index.html. Run the Vite build first.`,
  );
}

const entries = [];
let total = 0;
for (const file of await walk(source)) {
  if (file.endsWith(".map")) continue;
  const relative = `/${path.relative(source, file).split(path.sep).join("/")}`;
  const extension = path.extname(file).toLowerCase();
  const type = types[extension];
  if (!type) throw new Error(`Unsupported web asset type: ${relative}`);
  const bytes = await readFile(file);
  total += bytes.length;
  const text = /^(?:text\/|application\/json|image\/svg)/.test(type);
  entries.push({
    path: relative,
    type,
    encoding: text ? "utf8" : "base64",
    content: text ? bytes.toString("utf8") : bytes.toString("base64"),
  });
}
if (total > LIMIT)
  throw new Error(
    `Web assets are ${total} bytes, above the ${LIMIT} byte limit. Trim dependencies before bundling.`,
  );

const literal = JSON.stringify(
  Object.fromEntries(entries.map((entry) => [entry.path, entry])),
  null,
  2,
).replaceAll("</script", "<\\/script");
await mkdir(path.dirname(target), { recursive: true });
await writeFile(
  target,
  `// Generated by scripts/embed-web-assets.mjs. Do not edit.\nexport interface WebAsset {\n  path: string;\n  type: string;\n  encoding: "utf8" | "base64";\n  content: string;\n}\nexport const webAssets: Record<string, WebAsset> = ${literal};\n`,
);
process.stdout.write(
  `Embedded ${entries.length} web assets (${total} bytes) into ${path.relative(root, target)}\n`,
);
